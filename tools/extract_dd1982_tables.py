#!/usr/bin/env python3
"""Extract round layouts and speed tables from the 1982 Dig Dug (rev 2) ROM set.

Reads the owner's `digdug.zip` (never committed) and writes
`src/data/dd1982_tables.c`: the 15 round layouts and the monster speed tables,
converted to this port's 14x14 tile field. Only derived tables are emitted; no
ROM bytes are copied verbatim.

What the original stores (main CPU ROM, addresses in the rev 2 image):
  $3168  15 layouts x 8 tile-RAM pointers: 4 vertical then 4 horizontal tunnels
         (0 = unused). Round 1 tunnels are longer: 5 / 4 cells instead of 3 / 3.
  $3258  15 x 8 monster start bytes: slots 0-3 Pooka, 4-7 Fygar, 0 = empty.
  $30F0  15 x 8 rock start bytes, 0 = empty.
  Position bytes: low nibble = column + 1, high nibble = row - 1 (16 px cells).
Sub CPU ROM:
  $1BFE  surface-lane speed per difficulty bank (16 bytes) and round step.
  $1C3E  six speed tables, $40 apart: Pooka normal/mid/fast, Fygar normal/mid/fast.
  Speeds are 8-bit accumulator rates: a monster takes one 2-pixel step each
  time its accumulator borrows, and each monster is updated every other frame.

Original field: surface lane, then dirt rows 2..16 (strata of 4/4/4/3 rows).
The layouts only use rows 4..15, so this port keeps rows 3..15 as its 13 dirt
rows (strata 3/4/4/2): port row = original row - 2, columns unchanged.

Usage: python3 tools/extract_dd1982_tables.py [digdug.zip]
"""

from __future__ import annotations

import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "data" / "dd1982_tables.c"

LAYOUTS = 15
ROW_SHIFT = 2          # port row = original row - ROW_SHIFT
FIELD_W, FIELD_H = 14, 14
DIFFICULTY_BANK = 0    # DIP difficulty bank used for the committed tables
ROUND_STEPS = 15       # the original clamps its speed index at round 15


def load(zip_path: Path) -> tuple[bytes, bytes]:
    with zipfile.ZipFile(zip_path) as z:
        cpu0 = b"".join(z.read(n) for n in ("dd1a.1", "dd1a.2", "dd1a.3", "dd1a.4"))
        cpu1 = b"".join(z.read(n) for n in ("dd1a.5", "dd1a.6"))
    if len(cpu0) != 0x4000 or len(cpu1) != 0x2000:
        raise SystemExit("unexpected ROM sizes; expected the Namco rev 2 set (dd1a.*)")
    return cpu0, cpu1


def decode_layout(cpu0: bytes, c: int) -> dict:
    """Layout c (0-based) in port tile coordinates."""
    tunnels, cells = [], set()
    base = 0x3168 + c * 16
    for k, b in enumerate(range(8, 0, -1)):
        ptr = cpu0[base + 2 * k] | (cpu0[base + 2 * k + 1] << 8)
        if not ptr >> 8:
            continue
        offs = ptr - 0x8000
        u = (offs >> 5) - 2            # tile index along the original's unrotated Y
        v = (offs & 0x1F) + 2          # tile row on the rotated (displayed) screen
        if b >= 5:                     # vertical: two tile columns, 6 or 10 tiles tall
            length = (6 + (4 if c == 0 else 0)) // 2
            col, row = 13 - u // 2, v // 2 - ROW_SHIFT
            tunnels.append((col, row, length, 1))
            cells |= {(col, row + i) for i in range(length)}
        else:                          # horizontal: stamped towards lower columns
            length = (2 + (6 if c == 0 else 4)) // 2
            right, row = 13 - u // 2, v // 2 - ROW_SHIFT
            col = right - length + 1
            tunnels.append((col, row, length, 0))
            cells |= {(col + i, row) for i in range(length)}

    vertical_cells = {(t[0], t[1] + i) for t in tunnels if t[3] for i in range(t[2])}
    monsters = []
    for slot, m in enumerate(cpu0[0x3258 + c * 8: 0x3258 + c * 8 + 8]):
        if m:
            col, row = (m & 15) - 1, (m >> 4) + 1 - ROW_SHIFT
            monsters.append((col, row, 0 if slot < 4 else 1, 1 if (col, row) in vertical_cells else 0))
    rocks = [((r & 15) - 1, (r >> 4) + 1 - ROW_SHIFT)
             for r in cpu0[0x30F0 + c * 8: 0x30F0 + c * 8 + 8] if r]

    # Self-checks: everything on the field, monsters inside tunnels, rocks in dirt.
    for col, row, length, vert in tunnels:
        end_col, end_row = (col, row + length - 1) if vert else (col + length - 1, row)
        assert 0 <= col and end_col < FIELD_W and 1 <= row and end_row < FIELD_H, (c, tunnels)
    assert all((mc, mr) in cells for mc, mr, _, _ in monsters), (c, monsters)
    assert all(rk not in cells and 0 <= rk[0] < FIELD_W and 1 <= rk[1] < FIELD_H for rk in rocks), (c, rocks)
    assert len(tunnels) <= 6 and len(monsters) <= 8 and len(rocks) <= 5
    return {"tunnels": tunnels, "monsters": monsters, "rocks": rocks}


def emit(cpu0: bytes, cpu1: bytes) -> str:
    out = [
        "/*",
        " * Super Dig Dug — round layouts and monster speeds of the 1982 original.",
        " * GENERATED by tools/extract_dd1982_tables.py from the owner's ROM set;",
        " * do not edit by hand. Coordinates are port tiles (row 0 = surface lane).",
        " */",
        '#include "../world/sdd_world.h"',
        "",
        f"const sdd_round_def_t k_dd82_layouts[DD82_LAYOUT_COUNT] = {{",
    ]
    for c in range(LAYOUTS):
        lay = decode_layout(cpu0, c)
        pookas = sum(1 for m in lay["monsters"] if m[2] == 0)
        fygars = len(lay["monsters"]) - pookas
        out.append(f"    /* Layout {c + 1}: {pookas} Pooka, {fygars} Fygar, {len(lay['rocks'])} rocks */")
        out.append("    {")
        out.append(f"        {len(lay['tunnels'])}u, {len(lay['monsters'])}u, {len(lay['rocks'])}u,")
        out.append("        { " + ", ".join(f"{{ {a}u, {b}u, {n}u, {v}u }}" for a, b, n, v in lay["tunnels"]) + " },")
        out.append("        { " + ", ".join(
            f"{{ {a}u, {b}u, {'ENEMY_KIND_FYGAR' if k else 'ENEMY_KIND_POOKA'}, {v}u }}"
            for a, b, k, v in lay["monsters"]) + " },")
        out.append("        { " + ", ".join(f"{{ {a}u, {b}u }}" for a, b in lay["rocks"]) + " }")
        out.append("    },")
    out.append("};")
    out.append("")

    bank = DIFFICULTY_BANK * 16
    surface = list(cpu1[0x1BFE + bank: 0x1BFE + bank + ROUND_STEPS])
    tiers = [list(cpu1[0x1C3E + p * 0x40 + bank: 0x1C3E + p * 0x40 + bank + ROUND_STEPS]) for p in range(6)]
    out.append("/* Accumulator rates per round step (round 1..15, clamped). One 2-pixel")
    out.append(" * step per borrow; each monster is updated every other frame. */")
    out.append("const uint8_t k_dd82_speed_surface[DD82_ROUND_STEPS] = { " + ", ".join(map(str, surface)) + " };")
    out.append("/* [0..2] Pooka normal / mid / fast, [3..5] Fygar normal / mid / fast */")
    out.append("const uint8_t k_dd82_speed_tier[6][DD82_ROUND_STEPS] = {")
    for row in tiers:
        out.append("    { " + ", ".join(map(str, row)) + " },")
    out.append("};")
    out.append(f"const uint8_t k_dd82_speed_down_bonus = {cpu0[0x32EE]}u; /* added when heading down from round 4 */")
    out.append("")
    return "\n".join(out)


def main() -> int:
    zip_path = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "digdug.zip"
    if not zip_path.is_file():
        print(f"[dd1982] ROM set not found: {zip_path}", file=sys.stderr)
        return 1
    cpu0, cpu1 = load(zip_path)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(emit(cpu0, cpu1))
    print(f"[dd1982] wrote {OUT.relative_to(ROOT)} ({LAYOUTS} layouts, {ROUND_STEPS} speed steps)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
